        final wib = jadwal[w].toUtc().add(const Duration(hours: 7));
        final [h, m] = jam[i].split(':').map(int.parse).toList();
        final beda = wib.hour * 60 + wib.minute - (h * 60 + m);
        selisih.putIfAbsent(w, () => []).add(beda);
        if (beda.abs() > maks) maks = beda.abs();
      }
